########################################################################################################################
# Imports
########################################################################################################################


from . import properties, operators, menus


########################################################################################################################
# Registration
########################################################################################################################


modules = [
    properties,
    operators,
    menus,
]


def register():
    for module in modules:
        module.register()


def unregister():
    for module in reversed(modules):
        module.unregister()


if __name__ == "__main__":
    register()
